"""RBC 参数探索的 Case 表：固定 kappa=(1e5)^-1/2，降低 nu。Pr=1e5/Ra 时 kappa 不变（见 rb_equations: kappa=(Ra*Pr)^-1/2）。"""
KAPPA0 = 1e5 ** -0.5
# name: (Ra, nx, nz)；Pr = 1e5/Ra
CASES = {'base': (8e5, 72, 24), 'A': (1e6, 192, 96), 'B': (1e7, 256, 128), 'C': (1e8, 512, 256),
         'Bhi': (1e7, 384, 192),   # Bhi: Case B 的加密对照
         # 固定 Pr 的实验（与上面固定 kappa 的实验分开，不要混为一谈）：kappa=nu=Ra^-1/2
         'P1a': (3e6, 256, 128, 1.0), 'P1b': (1e7, 256, 128, 1.0), 'P1c': (1e8, 384, 192, 1.0),
         # 筛选：按 eta=sqrt(Pr)*(Ra(Nu-1))^-1/4 与 kmax*eta>=1 的判据挑的中间 Pr（固定 Pr，不固定 kappa）
         'S1': (1e7, 256, 128, 0.3), 'S2': (1e7, 384, 192, 0.1), 'S3': (3e7, 384, 192, 0.3), 'S4': (1e8, 512, 256, 0.3),
         'S3h': (3e7, 512, 256, 0.3),
         'S5': (1e8, 512, 256, 0.5), 'S6': (3e7, 384, 192, 0.5),
         'S4h': (1e8, 768, 384, 0.3),   # S4 的加密验证
         # 起始阶段长度实测：Pr=0.5，384x192，长时间运行
         'L1': (3e6, 384, 192, 0.5), 'L2': (1e7, 384, 192, 0.5), 'L3': (3e7, 384, 192, 0.5),
         # Ra=1e8 在 384x192 网格上（Pr=0.5 / 0.3），与 512x256 的 S5/S4 对照
         'M1': (1e8, 384, 192, 0.5), 'M2': (1e8, 384, 192, 0.3)}   # S4 的加密验证   # S3 的加密验证：看 S3 的伪影是否随分辨率消失
def params(name):
    c = CASES[name]; ra, nx, nz = c[:3]; pr = c[3] if len(c) > 3 else 1e5 / ra   # 默认固定 kappa（Pr=1e5/Ra）；第4项给出则固定该 Pr
    return dict(ra=ra, pr=pr, nx=nx, nz=nz, nu=(ra / pr) ** -0.5, kappa=(ra * pr) ** -0.5)
